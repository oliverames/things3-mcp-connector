// Builds src/things-list-app.generated.js: the MCP App view as one self-contained HTML string.
// Workers have no filesystem and the view's sandbox blocks external scripts, so the MCP Apps SDK
// browser client is inlined into src/app/things-list.html at the /*__SDK__*/ marker.
// Run `npm run build:app` after editing the view or upgrading @modelcontextprotocol/ext-apps.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const sdkPath = fileURLToPath(new URL("node_modules/@modelcontextprotocol/ext-apps/dist/src/app-with-deps.js", root));
const htmlPath = fileURLToPath(new URL("src/app/things-list.html", root));
const outPath = fileURLToPath(new URL("src/things-list-app.generated.js", root));

// Each src/app/glyphs/*.svg becomes a <symbol id="gl-NAME"> in one hidden sprite. Ids inside a glyph
// are prefixed so files cannot collide, and the black fill of template glyphs becomes currentColor
// so CSS can tint them.
export function buildSprite() {
  const dir = new URL("src/app/glyphs/", root);
  const symbols = readdirSync(dir).filter((f) => f.endsWith(".svg")).sort().map((file) => {
    const name = file.slice(0, -4);
    const svg = readFileSync(new URL(file, dir), "utf8");
    const m = /<svg\b[^>]*viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>/.exec(svg);
    if (!m) throw new Error(`${file}: not a pdftocairo SVG`);
    const prefix = `${name}__`;
    let inner = m[2]
      .replace(/\bid="([^"]+)"/g, (_, id) => `id="${prefix}${id}"`)
      .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${prefix}${id})`)
      .replace(/(xlink:)?href="#([^"]+)"/g, (_, x, id) => `href="#${prefix}${id}"`);
    if (/-Template$|-400$/.test(name)) inner = inner.replace(/rgb\(0%, 0%, 0%\)/g, "currentColor");
    return `<symbol id="gl-${name}" viewBox="${m[1]}">${inner}</symbol>`;
  });
  return `<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">${symbols.join("")}</svg>`;
}

export async function buildHtml() {
  let sdk = readFileSync(sdkPath, "utf8");
  // The prebuilt bundle ends in one `export{a as App, ...}`. An inline script cannot be imported
  // from, so turn that clause into a plain object the view destructures.
  const m = /export\s*\{([^}]*)\}\s*;?\s*$/.exec(sdk);
  if (!m) throw new Error("SDK bundle has no trailing export clause; update scripts/build-app.mjs");
  const pairs = m[1].split(",").map((p) => p.trim()).filter(Boolean).map((p) => {
    const [local, exported = local] = p.split(/\s+as\s+/);
    return `${JSON.stringify(exported)}:${local}`;
  });
  // The bundle is already minified. Wrap it in a function so its top-level names cannot collide
  // with the view's own.
  const code = `const __sdk=(()=>{\n${sdk.slice(0, m.index)}\nreturn {${pairs.join(",")}};\n})();`;
  // A script body must never contain a closing tag or an HTML comment opener.
  const safe = code.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");
  const html = readFileSync(htmlPath, "utf8");
  if (!html.includes("/*__SDK__*/")) throw new Error("view is missing the /*__SDK__*/ marker");
  if (!html.includes("<!--__GLYPHS__-->")) throw new Error("view is missing the <!--__GLYPHS__--> marker");
  return html.replace("/*__SDK__*/", () => safe).replace("<!--__GLYPHS__-->", () => buildSprite());
}

export function moduleSource(html) {
  return `// GENERATED by scripts/build-app.mjs from src/app/things-list.html. Do not edit by hand.\nexport const THINGS_LIST_HTML = ${JSON.stringify(html)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = await buildHtml();
  writeFileSync(outPath, moduleSource(html));
  console.log(`wrote ${outPath} (${(html.length / 1024).toFixed(0)} KiB)`);
}
